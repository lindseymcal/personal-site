function homeSpines(books, colorFor, capacities, tierHeight, leanFirstTier) {
  const picked = selectHomeShelf(books, 80).map((b) => {
    const st = spineStyle(b, colorFor(b));
    return { st, book: b, lay: homeSpineLayout(b, st, tierHeight) };
  });
  // newest books, shown oldest to newest left to right, top shelf to bottom shelf
  const tiers = packNewestChronologically(picked.map((p) => p.lay.width + 2), capacities);
  return tiers.map((idx, t) => idx.map((i, k) => ({
    ...picked[i],
    lean: leanFirstTier && t === 0 && k === idx.length - 1 && idx.length > 1,
  })));
}

