function document_({ title, base = '', css = [], fonts = FONTS_BASE, htmlClass = '', stageH = 800, scene = true, bodyClass = '', body }) {
  const tall = scene && stageH > 800;
  const classes = [scene ? 'scene' : '', htmlClass, tall ? 'tall' : ''].filter(Boolean).join(' ');
  return `<!doctype html>
<html lang="en"${classes ? ` class="${classes}"` : ''}${tall ? ` data-stage-h="${stageH}"` : ''}>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?${fonts}&display=swap" rel="stylesheet">
<link rel="stylesheet" href="${base}assets/site.css">
${css.map((c) => `<link rel="stylesheet" href="${base}assets/${c}.css">`).join('\n')}
${scene ? FIT_SCRIPT : ''}
</head>
<body${bodyClass ? ` class="${bodyClass}"` : ''}>
${body}
</body>
</html>
`;
}

