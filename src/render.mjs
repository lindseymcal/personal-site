// --- books ------------------------------------------------------------------------------------

const ROW_HEIGHT = 348;
const SPINE_GAP = 3;
const ROW_CAPACITY = 1022 - 26; // tier width inside its padding, minus the bookend at the end

// Letters, digits, - and _ only: safe inside an id and a CSS selector.
export function bookDomId(id) {
  return String(id).replace(/[^A-Za-z0-9_-]/g, '') || 'x';
}

function dotsHtml(rating) {
  if (rating < 1) return '';
  const dots = Array.from({ length: 5 }, (_, i) => `<i${i < rating ? '' : ' class="o"'}></i>`).join('');
  return `<span class="dots" role="img" aria-label="${rating} out of 5">${dots}</span>`;
}

function spineHtml(book, st, { lean = false } = {}) {
  const id = bookDomId(book.id);
  const label = `${book.title}, ${book.author}${book.favorite ? ', a favorite' : ''}`;
  const vars = `--w:${st.width}px;--h:${st.height}px;--c:${st.bg};--t:${st.text};${st.band ? `--band:${st.band};` : ''}--f:'${st.family}';--fs:${st.fontSize}px${st.caps ? ';--tt:uppercase' : ''}`;
  return `<a class="spine${book.favorite ? ' is-fav' : ''}${lean ? ' lean' : ''}" id="s-${id}" href="#b-${id}" aria-label="${esc(label)}" style="${vars}">${book.favorite ? '<i class="foil" aria-hidden="true"></i>' : ''}<span class="t">${esc(book.spineTitle)}</span><span class="a">${esc(book.spineAuthor)}</span></a>`;
}

function pulledBookHtml(book, st) {
  const id = bookDomId(book.id);
  const hasReview = reviewToHtml(book.review) !== '';
  const fav = book.favorite;
  const dots = dotsHtml(book.rating);
  const row = dots || book.when
    ? `<div class="row">${dots}${book.when ? `<span class="when">${esc(book.when)}</span>` : ''}</div>`
    : '';
  const heading = `<h2>${esc(book.title)}${fav ? '<i class="foil big" role="img" aria-label="A favorite"></i>' : ''}</h2>`;
  const by = `<p class="by">${esc(book.author)}</p>`;
  const slip = book.recommendedBy ? `<div class="slip"><i>recommended by ${esc(book.recommendedBy)}</i></div>` : '';
  const cover = `<div class="book" style="background:${st.bg};color:${st.text};font-family:'${st.family}'"><i class="frame"></i>${fav ? '<i class="foil" aria-hidden="true"></i>' : ''}<b style="${fav ? 'margin-top:34px;' : ''}font-size:${coverFontSize(book.title)}px${st.caps ? ';text-transform:uppercase' : ''}">${esc(book.spineTitle)}</b><span>${esc(book.author)}</span></div>`;
  const article = hasReview
    ? `<article class="letter" tabindex="0">\n      ${heading}\n      ${by}\n      ${row}\n      ${reviewToHtml(book.review)}\n    </article>`
    : `<article class="card">\n      ${heading}\n      ${by}\n      ${row}\n    </article>`;
  return `  <section class="pull" id="b-${id}" aria-label="${esc(`${book.title}, ${book.author}`)}">
    <a class="scrim" href="#shelf" aria-label="Put the book back"></a>
    ${cover}
    ${slip}
    ${article}
  </section>`;
}

// Works out the rows of spines for the whole shelf (pure, so a test can check it).
export function planShelf(groups, styleFor) {
  const rows = [];
  for (const group of groups) {
    const styles = group.books.map(styleFor);
    const packed = packIntoRows(styles.map((s) => s.width + SPINE_GAP), ROW_CAPACITY);
    packed.forEach((idx, r) => {
      rows.push({
        label: group.label,
        first: r === 0,
        items: idx.map((i) => ({ book: group.books[i], st: styles[i] })),
        used: idx.reduce((sum, i) => sum + styles[i].width + SPINE_GAP, 0),
      });
    });
  }
  return rows;
}

export function renderBooks({ config, groups, colorFor }) {
  const rows = planShelf(groups, (b) => spineStyle(b, colorFor(b)));
  const rowCount = Math.max(2, rows.length);
  const caseHeight = rowCount * ROW_HEIGHT + 44;
  const stageH = Math.max(800, 34 + caseHeight + 26);

  const tiers = rows.map((row, r) => {
    const leftover = ROW_CAPACITY - row.used;
    const lastIdx = row.items.length - 1;
    const roomForLean = r === 0 && leftover >= 130 && row.items.length > 1;
    const spines = row.items.map((it, k) => spineHtml(it.book, it.st, { lean: roomForLean && k === lastIdx })).join('\n        ');
    const decor = r === 0 && leftover >= 130 ? '<span class="plant" aria-hidden="true"></span>' : '<span class="bookend" aria-hidden="true"></span>';
    return `      <div class="tier" role="group" aria-label="${row.first ? `Read in ${esc(row.label)}` : `Read in ${esc(row.label)}, continued`}">
        ${spines}
        ${decor}
        ${row.first ? `<span class="plate" aria-hidden="true">${esc(row.label)}</span>` : ''}
      </div>`;
  });
  while (tiers.length < 2) tiers.push('      <div class="tier"><span class="bookend" aria-hidden="true"></span></div>');

  const allBooks = groups.flatMap((g) => g.books);
  const pulls = allBooks.map((b) => pulledBookHtml(b, spineStyle(b, colorFor(b)))).join('\n\n');
  const gapSelectors = allBooks.map((b) => `.stage:has(#b-${bookDomId(b.id)}:target) #s-${bookDomId(b.id)}`);
  const gapStyle = gapSelectors.length
    ? `<style>\n${gapSelectors.join(',\n')}{background:transparent!important;background-image:none!important;box-shadow:inset 0 0 0 2px rgba(245,206,122,.55),inset 0 0 22px rgba(245,206,122,.25)}\n${gapSelectors.map((s) => `${s} > *`).join(',\n')}{visibility:hidden}\n</style>`
    : '';

  return GENERATED_NOTE + document_({
    title: `Books, ${config.name}`,
    css: ['books'],
    fonts: FONTS_BOOKS,
    htmlClass: 'p-books',
    stageH,
    body: `<div class="fit"><div class="stage books" id="shelf" style="height:${stageH}px">
  ${homeWindow('')}
  <main>
    <h1 class="sr">Books</h1>
    <div class="case" style="--rows:${rowCount}">
${tiers.join('\n')}
    </div>
  </main>

${pulls}
</div></div>
${gapStyle}`,
  });
}

